"""Generate the dashboard's TypeScript types for the typed API from apps/api/dto.py.

    python scripts/gen_dashboard_types.py            # writes apps/dashboard/src/dto.ts
    python scripts/gen_dashboard_types.py --check    # exit 1 when the file is out of date

One source of truth: the Pydantic response models the API declares (schema recap-api-v1)
become TypeScript interfaces, so the dashboard reads exactly what the server sends. Every
model the DTOs reach is emitted (the evaluation records included), except the core models
the dashboard already types by hand in src/types.ts (the run record, evidence, ...), which are
imported from there. tests/unit/test_dashboard_types.py fails when dto.ts is out of date.

Every field is required in TypeScript: the API serializes each model with all its fields
(model_dump), so a field with a default is still always present.
"""

from __future__ import annotations

import argparse
import enum
import re
import sys
import types
import typing
from datetime import date, datetime
from pathlib import Path
from typing import Any, Literal, get_args, get_origin

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # allow running without install

from pydantic import BaseModel

from apps.api import dto

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "apps" / "dashboard" / "src" / "dto.ts"
HAND_TYPES = ROOT / "apps" / "dashboard" / "src" / "types.ts"

HEADER = """\
// GENERATED by scripts/gen_dashboard_types.py from apps/api/dto.py (schema {schema}).
// Do not edit by hand: change the response models in apps/api/dto.py, then run
//     .venv/bin/python scripts/gen_dashboard_types.py
// tests/unit/test_dashboard_types.py fails when this file is out of date.
"""


def _hand_typed() -> set[str]:
    """The type names src/types.ts already exports (written by hand for older endpoints)."""
    text = HAND_TYPES.read_text(encoding="utf-8")
    return set(re.findall(r"^export (?:interface|type) (\w+)", text, flags=re.MULTILINE))


class Emitter:
    def __init__(self, hand: set[str]) -> None:
        self.hand = hand
        self.imports: set[str] = set()
        self.models: dict[str, type[BaseModel]] = {}  # name -> model, in emission order
        self.aliases = {
            name: value
            for name, value in vars(dto).items()
            if not name.startswith("_") and get_origin(value) is Literal
        }

    # --- type expressions ---------------------------------------------------------------

    def ts(self, annotation: Any) -> str:
        if annotation is type(None) or annotation is None:
            return "null"
        for name, alias in self.aliases.items():
            if annotation == alias:
                return name
        origin = get_origin(annotation)
        if origin is Literal:
            return " | ".join(_literal(v) for v in get_args(annotation))
        if origin in (typing.Union, types.UnionType):
            parts = list(dict.fromkeys(self.ts(a) for a in get_args(annotation)))
            return " | ".join(parts)
        if origin in (list, set, frozenset, typing.Sequence) or annotation in (list, set):
            (inner,) = get_args(annotation) or (Any,)
            return f"{_group(self.ts(inner))}[]"
        if origin is tuple:
            args = get_args(annotation)
            if len(args) == 2 and args[1] is Ellipsis:
                return f"{_group(self.ts(args[0]))}[]"
            return "[" + ", ".join(self.ts(a) for a in args) + "]"
        if origin in (dict, typing.Mapping) or annotation is dict:
            args = get_args(annotation)
            value = self.ts(args[1]) if len(args) == 2 else "unknown"
            return f"Record<string, {value}>"
        if annotation in (str,):
            return "string"
        if annotation in (int, float):
            return "number"
        if annotation is bool:
            return "boolean"
        if annotation in (datetime, date):
            return "string"
        if annotation is Any or annotation is object:
            return "unknown"
        if isinstance(annotation, type) and issubclass(annotation, enum.Enum):
            name = annotation.__name__
            if name in self.hand:
                self.imports.add(name)
                return name
            return " | ".join(_literal(m.value) for m in annotation)
        if isinstance(annotation, type) and issubclass(annotation, BaseModel):
            name = annotation.__name__
            if annotation.__module__ != dto.__name__ and name in self.hand:
                self.imports.add(name)
                return name
            self.add(annotation)
            return name
        raise TypeError(f"no TypeScript mapping for {annotation!r}")

    # --- models ------------------------------------------------------------------------

    def add(self, model: type[BaseModel]) -> None:
        name = model.__name__
        if name in self.models:
            return
        self.models[name] = model
        for field in model.model_fields.values():
            self.ts(field.annotation)  # pull in every model a field reaches

    def interface(self, model: type[BaseModel]) -> str:
        lines = []
        paragraph = (model.__doc__ or "").strip().split("\n\n")[0]
        doc = " ".join(line.strip() for line in paragraph.splitlines()).replace("*/", "* /")
        if doc:
            lines.append(f"/** {doc} */")
        bases = [
            b.__name__
            for b in model.__bases__
            if issubclass(b, BaseModel) and b is not BaseModel and b.__name__ in self.models
        ]
        inherited = {
            f for b in model.__bases__ if b in self.models.values() for f in b.model_fields
        }
        extends = f" extends {', '.join(bases)}" if bases else ""
        lines.append(f"export interface {model.__name__}{extends} {{")
        for field_name, field in model.model_fields.items():
            if field_name in inherited:
                continue
            lines.append(f"  {field_name}: {self.ts(field.annotation)};")
        lines.append("}")
        return "\n".join(lines)


def _literal(value: Any) -> str:
    if isinstance(value, enum.Enum):
        value = value.value
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int | float):
        return repr(value)
    return '"' + str(value).replace("\\", "\\\\").replace('"', '\\"') + '"'


def _group(expression: str) -> str:
    return f"({expression})" if "|" in expression else expression


def generate() -> str:
    emitter = Emitter(_hand_typed())
    models = [
        value
        for value in vars(dto).values()
        if isinstance(value, type)
        and issubclass(value, BaseModel)
        and value.__module__ == dto.__name__
    ]
    for model in models:
        emitter.add(model)
    body = [
        f"export type {name} = {' | '.join(_literal(v) for v in get_args(alias))};"
        for name, alias in emitter.aliases.items()
    ]
    body += ["", f'export const API_SCHEMA: ApiSchema = "{dto.API_SCHEMA}";', ""]
    body += [emitter.interface(model) + "\n" for model in emitter.models.values()]
    head = HEADER.format(schema=dto.API_SCHEMA)
    if emitter.imports:
        head += f'\nimport type {{ {", ".join(sorted(emitter.imports))} }} from "./types";\n'
    return head + "\n" + "\n".join(body).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail when dto.ts is out of date")
    args = parser.parse_args(argv)
    text = generate()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run scripts/gen_dashboard_types.py")
            return 1
        print(f"{OUT.relative_to(ROOT)} matches apps/api/dto.py")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({text.count('export interface')} interfaces)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
